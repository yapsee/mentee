-- "order" is a reserved word in SQL, so the table is customer_order.

CREATE TABLE customer_order
(
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference          VARCHAR(50)    NOT NULL UNIQUE,
    total_amount       NUMERIC(12, 2) NOT NULL CHECK (total_amount > 0),
    payment_method     VARCHAR(30)    NOT NULL,
    -- A customer id from customer-service (MongoDB). No foreign key: the customer lives in another database.
    customer_id        VARCHAR(50)    NOT NULL,
    created_date       TIMESTAMP      NOT NULL,
    last_modified_date TIMESTAMP
);

CREATE TABLE order_line
(
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   INTEGER NOT NULL REFERENCES customer_order (id) ON DELETE CASCADE,
    -- A product id from product-service. No foreign key across services either.
    product_id INTEGER NOT NULL,
    quantity   INTEGER NOT NULL CHECK (quantity > 0)
);

CREATE INDEX idx_order_customer ON customer_order (customer_id);
CREATE INDEX idx_order_line_order ON order_line (order_id);
